//! 同和中学校运会积分系统（Rust 版）库入口。
//!
//! # 为什么需要这个文件
//!
//! 本项目的产物是一个可执行文件（`src/main.rs`），但集成测试
//! （`tests/*.rs`）在**独立的 crate** 里编译，无法访问二进制 crate 的
//! 模块。加密信道的双端契约测试必须能直接调用客户端的 `seal`/`open`，
//! 因此这里把与二进制**完全相同**的模块树再暴露一份为库目标。
//!
//! 两份声明必须保持同步：`main.rs` 里的 `mod core; mod extensions;`
//! 与这里指向同一批文件，改一处即改两处（同一源文件，不会分叉）。

pub mod core;
pub mod extensions;
